from typing import Optional, List, TYPE_CHECKING
from datetime import datetime, timezone
from decimal import Decimal
from sqlalchemy import CheckConstraint, Column, Computed, Index, Numeric
from sqlmodel import Field, SQLModel, Relationship
from app.backend.enums.general import ObservationStatus, ConfidenceLevel

if TYPE_CHECKING:
    from app.backend.models.user import User
    from app.backend.models.post import Post
    from app.backend.models.media import MediaFile


class ObservationTag(SQLModel, table=True):
    """Link table for many-to-many relationship between observations and tags"""
    __tablename__ = "observation_tags"

    observation_id: int = Field(foreign_key="observations.id", primary_key=True)
    tag_id: int = Field(foreign_key="tags.id", primary_key=True)


class Tag(SQLModel, table=True):
    __tablename__ = "tags"

    id: Optional[int] = Field(default=None, primary_key=True)
    name: str = Field(max_length=100, index=True, unique=True)
    is_deleted: bool = Field(default=False)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    # Relationships
    observations: List["Observation"] = Relationship(
        back_populates="tags",
        link_model=ObservationTag
    )


class Category(SQLModel, table=True):
    __tablename__ = "categories"

    id: Optional[int] = Field(default=None, primary_key=True)
    name: str = Field(max_length=255, index=True, unique=True)
    alias: str = Field(max_length=255)
    is_deleted: bool = Field(default=False)

    # Relationships
    signal_types: List["SignalType"] = Relationship(back_populates="category")


class SignalType(SQLModel, table=True):
    __tablename__ = "signal_types"

    id: Optional[int] = Field(default=None, primary_key=True)
    code: str = Field(unique=True, index=True, max_length=50)
    name: str = Field(max_length=255)
    category_id: Optional[int] = Field(default=None, foreign_key="categories.id", index=True)
    description: Optional[str] = Field(default=None, max_length=1000)
    is_active: bool = Field(default=True, index=True)
    sort_order: int = Field(default=0, index=True)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    is_deleted: bool = Field(default=False)

    # Relationships
    category: Optional[Category] = Relationship(back_populates="signal_types")
    observations: List["Observation"] = Relationship(back_populates="signal_type")

    @property
    def category_name(self) -> Optional[str]:
        """Convenience property to get category name"""
        return self.category.name if self.category else None


class ObservationFrequency(SQLModel, table=True):
    """One frequency band of an observation (kind = rc, video, ...).

    is_deleted marks a band removed from its observation. Whether the band is
    visible also depends on observations.is_deleted: always read bands through
    ObservationFrequencyFilter, which joins the observation, its archive flag
    and the post scope.
    """
    __tablename__ = "observation_frequencies"
    __table_args__ = (
        CheckConstraint("frequency_min > 0", name="ck_observation_frequencies_min_positive"),
        CheckConstraint("frequency_max > frequency_min", name="ck_observation_frequencies_max_above_min"),
        CheckConstraint("frequency_center > 0", name="ck_observation_frequencies_center_positive"),
        Index("ix_observation_frequencies_observation_active", "observation_id", "is_deleted"),
        Index("ix_observation_frequencies_kind_center", "kind", "frequency_center"),
        Index("ix_observation_frequencies_center", "frequency_center"),
    )
    # Read the generated bandwidth back inside the flush (no lazy load later in async code)
    __mapper_args__ = {"eager_defaults": True}

    id: Optional[int] = Field(default=None, primary_key=True)
    observation_id: int = Field(foreign_key="observations.id")
    kind: str = Field(max_length=20)
    # Optional: bands sharing a number describe one emitter (e.g. RC and video of one drone)
    link_group: Optional[int] = Field(default=None)

    frequency_min: Decimal = Field(decimal_places=3, max_digits=12)
    frequency_max: Decimal = Field(decimal_places=3, max_digits=12)
    frequency_center: Decimal = Field(decimal_places=3, max_digits=12)
    # Generated by the database, never written by the API
    bandwidth: Optional[Decimal] = Field(
        default=None,
        sa_column=Column(Numeric(12, 3), Computed("frequency_max - frequency_min", persisted=True)),
    )

    is_deleted: bool = Field(default=False)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    observation: "Observation" = Relationship(back_populates="all_frequencies")


class Observation(SQLModel, table=True):
    __tablename__ = "observations"
    __table_args__ = (
        # Observation counters of a post: post_id =, is_deleted =, created_at range (services/observation_counts.py)
        Index("ix_observations_post_deleted_created", "post_id", "is_deleted", "created_at"),
    )

    id: Optional[int] = Field(default=None, primary_key=True)
    user_id: int = Field(foreign_key="users.id", index=True)
    post_id: int = Field(foreign_key="posts.id", index=True)
    signal_type_id: int = Field(foreign_key="signal_types.id", index=True)

    observed_at: datetime = Field(index=True)
    duration_seconds: Optional[int] = Field(default=None)

    comment: Optional[str] = Field(default=None, max_length=1000)

    status: str = Field(default=ObservationStatus.ACTIVE.value, index=True, max_length=20)
    confidence_level: str = Field(default=ConfidenceLevel.MEDIUM.value, max_length=10)
    is_deleted: bool = Field(default=False)

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), index=True)
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    disappeared_at: Optional[datetime] = Field(default=None, index=True)
    disappeared_by: Optional[int] = Field(default=None, foreign_key="users.id")

    # Relationships
    user: "User" = Relationship(
        back_populates="observations",
        sa_relationship_kwargs={"foreign_keys": "[Observation.user_id]"}
    )
    post: "Post" = Relationship(back_populates="observations")
    signal_type: SignalType = Relationship(back_populates="observations")
    disappeared_by_user: Optional["User"] = Relationship(
        back_populates="disappeared_observations",
        sa_relationship_kwargs={"foreign_keys": "[Observation.disappeared_by]"}
    )
    media_files: List["MediaFile"] = Relationship(back_populates="observation", cascade_delete=True)
    tags: List[Tag] = Relationship(
        back_populates="observations",
        link_model=ObservationTag
    )
    # Every band, archived ones included; responses use `frequencies`
    all_frequencies: List[ObservationFrequency] = Relationship(
        back_populates="observation",
        sa_relationship_kwargs={"order_by": "ObservationFrequency.id"},
    )

    @property
    def frequencies(self) -> List[ObservationFrequency]:
        """Bands that are not archived, in insertion order"""
        return [f for f in self.all_frequencies if not f.is_deleted] if self.all_frequencies else []

    @property
    def media_ids(self) -> List[int]:
        """IDs of attached media files; archived files stay linked but are not listed"""
        return [m.id for m in self.media_files if not m.is_deleted] if self.media_files else []

    @property
    def tag_ids(self) -> List[int]:
        """Convenience property to get IDs of attached tags"""
        return [t.id for t in self.tags] if self.tags else []
