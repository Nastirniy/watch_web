class ObservationReportParams(BaseModel):
    """
    Filter parameters for generating an observation Excel report.

    Supports filtering by:
    - Specific observation IDs
    - User IDs (one or many)
    - Post IDs (one or many)
    - Signal type IDs
    - Statuses
    - Observed-at date range
    - Created-at date range
    - Any combination of the above
    """

    # A misspelt filter answers 422 instead of widening the report unnoticed
    model_config = ConfigDict(extra="forbid")

    # --- Observation ID filter ---
    observation_ids: Optional[List[int]] = Field(
        default=None,
        description="Specific observation IDs to include in report"
    )

    # --- User filter ---
    user_ids: Optional[List[int]] = Field(
        default=None,
        description="Include only observations by these user IDs"
    )

    # --- Post filter ---
    post_ids: Optional[List[int]] = Field(
        default=None,
        description="Include only observations from these post IDs"
    )

    # --- Corps and brigades (placement: which unit an observation belongs to) ---
    corps_ids: Optional[List[int]] = Field(
        default=None, description="Include only observations of these corps, their brigades included (see placement)")
    brigade_ids: Optional[List[int]] = Field(
        default=None, description="Include only observations of these brigades (see placement)")
    placement: UnitPlacement = Field(
        default=UnitPlacement.RECORDED,
        description="Which unit corps_ids / brigade_ids match and the corps and brigade columns show: recorded (where "
                    "the post was when the observation was created) or current (where the post is now, archived posts "
                    "left out of the unit filters). Not a time filter")

    # --- Signal type filter ---
    signal_type_ids: Optional[List[int]] = Field(
        default=None,
        description="Include only observations of these signal type IDs"
    )

    # --- Status filter ---
    statuses: Optional[List[ObservationStatus]] = Field(default=None, description="Filter by statuses")

    # --- Confidence level filter ---
    confidence_level: Optional[ConfidenceLevel] = Field(default=None, description="Filter by confidence level")

    # --- Band range (applies to the bands of the report's kind; every kind for all_fields) ---
    frequency_center_from: Optional[Decimal] = Field(default=None, description="Band center frequency >= (MHz)")
    frequency_center_to: Optional[Decimal] = Field(default=None, description="Band center frequency <= (MHz)")
    bandwidth_from: Optional[Decimal] = Field(default=None, description="Bandwidth >= (MHz)")
    bandwidth_to: Optional[Decimal] = Field(default=None, description="Bandwidth <= (MHz)")

    # --- Duration range ---
    duration_from: Optional[int] = Field(default=None, ge=0, description="Duration >= (seconds)")
    duration_to: Optional[int] = Field(default=None, ge=0, description="Duration <= (seconds)")

    # --- Tag filter ---
    tag_ids: Optional[List[int]] = Field(default=None, description="Include only observations with these tag IDs; tag_match says whether any or all of them")
    tag_match: TagMatch = Field(default=TagMatch.ANY, description="any: observations with at least one of tag_ids; all: with every one of them")

    # --- Date range (observed_at) ---
    observed_at_from: Optional[UtcDatetime] = Field(
        default=None,
        description="Include observations with observed_at >= this value (ISO datetime, UTC)"
    )
    observed_at_to: Optional[UtcDatetime] = Field(
        default=None,
        description="Include observations with observed_at <= this value (ISO datetime, UTC)"
    )

    # --- Date range (created_at) ---
    created_at_from: Optional[UtcDatetime] = Field(
        default=None,
        description="Include observations with created_at >= this value (ISO datetime, UTC)"
    )
    created_at_to: Optional[UtcDatetime] = Field(
        default=None,
        description="Include observations with created_at <= this value (ISO datetime, UTC)"
    )

    # --- Report type (required) ---
    report_type: ObservationReportType = Field(
        description="'rc_freq_part' - rc bands; 'video_freq_part' - video bands; 'all_fields' - every band, all fields"
    )

    # --- Soft delete ---
    include_deleted: bool = Field(
        default=False,
        description="Include archived observations and archived bands in the report (requires observation.archive)"
    )
