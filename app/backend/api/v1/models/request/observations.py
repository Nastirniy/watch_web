from typing import Optional, List
from datetime import datetime, timezone
from decimal import Decimal, ROUND_HALF_UP
from pydantic import BaseModel, ConfigDict, Field, ValidationInfo, field_validator, model_validator, PositiveInt

from app.backend.enums.general import (ConfidenceLevel, FrequencyKind, ObservationReportType, ObservationStatus, TagMatch,
                                      UnitPlacement)
from app.backend.errors.coded import invalid
from app.backend.utils.validators import INT_MAX, ObservationTime, SecurityValidators, UtcDatetime, not_null
from app.backend.enums.errors import FieldErrorCode

FREQUENCY_QUANTUM = Decimal("0.001")
COMMENT_DESCRIPTION = ("Comment, multi-line plain text up to 1000 characters: line breaks and tabs kept, other control "
                       "characters (text_control_character) and script patterns (text_script_pattern) refused")


def _comment(value: Optional[str]) -> Optional[str]:
    return SecurityValidators.plain_text(value, max_length=1000, multiline=True) if value is not None else value


def default_frequency_center(frequency_min: Decimal, frequency_max: Decimal) -> Decimal:
    """Middle of the band, rounded to the column precision (3 decimals)"""
    return ((frequency_min + frequency_max) / 2).quantize(FREQUENCY_QUANTUM, rounding=ROUND_HALF_UP)


class ObservationFrequencyCreate(BaseModel):
    """One frequency band. Values in MHz with the DB precision: decimal_places=3, max_digits=12.
    bandwidth is generated by the database (frequency_max - frequency_min)."""

    kind: FrequencyKind = Field(description="Band kind: rc or video")
    frequency_min: Decimal = Field(gt=0, max_digits=12, decimal_places=3, description="Minimum frequency in MHz")
    frequency_max: Decimal = Field(gt=0, max_digits=12, decimal_places=3, description="Maximum frequency in MHz")
    frequency_center: Optional[Decimal] = Field(
        None,
        gt=0,
        max_digits=12,
        decimal_places=3,
        description="Center frequency in MHz; the middle of the band when omitted"
    )
    link_group: Optional[int] = Field(
        None,
        ge=1,
        le=INT_MAX,
        description="Optional: bands with the same number inside one observation belong to one emitter"
    )

    @field_validator('frequency_center')
    @classmethod
    def validate_center(cls, v: Optional[Decimal], info: ValidationInfo) -> Optional[Decimal]:
        """Checked against the band when min and max are valid; a center outside would hide the band from range filters"""
        low, high = info.data.get("frequency_min"), info.data.get("frequency_max")
        if v is not None and low is not None and high is not None and low < high and not low <= v <= high:
            raise invalid(FieldErrorCode.FREQUENCY_CENTER_OUT_OF_RANGE)
        return v

    @model_validator(mode='after')
    def validate_band(self):
        if self.frequency_min >= self.frequency_max:
            raise invalid(FieldErrorCode.FREQUENCY_RANGE_INVALID)
        if self.frequency_center is None:
            self.frequency_center = default_frequency_center(self.frequency_min, self.frequency_max)
        return self


class ObservationFrequencyUpdate(BaseModel):
    """Partial update of one band. The merged band is checked again (frequency_max > frequency_min, the center inside).
    When min or max changes and frequency_center is not sent, the center is recalculated."""

    kind: Optional[FrequencyKind] = Field(None, description="Band kind: rc or video")
    frequency_min: Optional[Decimal] = Field(None, gt=0, max_digits=12, decimal_places=3, description="Minimum frequency in MHz")
    frequency_max: Optional[Decimal] = Field(None, gt=0, max_digits=12, decimal_places=3, description="Maximum frequency in MHz")
    frequency_center: Optional[Decimal] = Field(None, gt=0, max_digits=12, decimal_places=3, description="Center frequency in MHz")
    link_group: Optional[int] = Field(None, ge=1, le=INT_MAX, description="Emitter group inside the observation; null clears it")

    # Only link_group may be cleared with null
    refuse_null = not_null("kind", "frequency_min", "frequency_max", "frequency_center")


class ObservationCreate(BaseModel):
    """Create observation with proper validation matching DB constraints"""

    post_id: int = Field(gt=0, description="Post ID must be positive")
    signal_type_id: int = Field(gt=0, description="Signal Type ID must be positive")

    frequencies: List[ObservationFrequencyCreate] = Field(
        min_length=1,
        description="Frequency bands of the observation, at least one (any kind)"
    )

    observed_at: ObservationTime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="When the signal was observed, "
                    "between 2000-01-01T00:00:00Z and now + 1 day (422 time_out_of_range); the current UTC time when omitted"
    )
    duration_seconds: Optional[int] = Field(None, ge=0, le=INT_MAX, description="Duration must be non-negative")
    comment: Optional[str] = Field(None, max_length=1000, description=COMMENT_DESCRIPTION)
    confidence_level: Optional[str] = Field(
        None,
        max_length=10,
        description="Confidence level: low, medium, or high"
    )
    tag_ids: Optional[List[PositiveInt]] = Field(
        None,
        description="List of tag IDs to associate with the observation (duplicates removed automatically)"
    )

    @field_validator('tag_ids')
    @classmethod
    def validate_tag_ids(cls, v: Optional[List[int]]) -> Optional[List[int]]:
        """Validate and deduplicate tag IDs"""
        if v is not None:
            return list(dict.fromkeys(v))
        return v

    @field_validator('comment')
    @classmethod
    def validate_comment(cls, v: Optional[str]) -> Optional[str]:
        return _comment(v)

    @field_validator('confidence_level')
    @classmethod
    def validate_confidence_level(cls, v: Optional[str]) -> Optional[str]:
        """Validate confidence level against enum values"""
        if v is not None:
            valid_levels = [level.value for level in ConfidenceLevel]
            if v not in valid_levels:
                raise invalid(FieldErrorCode.CONFIDENCE_LEVEL_INVALID, accepted=list(valid_levels))
        return v


